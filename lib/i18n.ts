export function translate(
  lang: Lang,
  key: string,
  params?: Record<string, string | number>,
): string {
  const entry = DICT[key];
  if (!entry) return key;
  let out = entry[lang];
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      out = out.split(`{${k}}`).join(String(v));
    }
  }
  return out;
}

/** Localizes short chart/weekday/month/donut labels ("Mon", "W1", "Telegram"). */
export function localizeLabel(lang: Lang, label: string): string {
  const entry = CHART_LABELS[label];
  if (!entry) return label;
  return entry[lang];
}

/** Localizes a relative-time string like "2m ago", "now", "yesterday". */
export function timeAgo(lang: Lang, value: string): string {
  if (lang === "en") return value;
  const now: Record<string, string> = {
    now: "الآن",
    today: "اليوم",
    yesterday: "أمس",
  };
  if (now[value]) return now[value];
  const match = /^(\d+)\s*([mhd])\s*(?:ago)?$/i.exec(value);
  if (!match) return value;
  const n = Number(match[1]);
  const unit = match[2].toLowerCase();
  if (unit === "m") {
    if (n === 1) return "منذ دقيقة";
    if (n === 2) return "منذ دقيقتين";
    return `منذ ${n} ${n >= 3 && n <= 10 ? "دقائق" : "دقيقة"}`;
  }
  if (unit === "h") {
    if (n === 1) return "منذ ساعة";
    if (n === 2) return "منذ ساعتين";
    return `منذ ${n} ${n >= 3 && n <= 10 ? "ساعات" : "ساعة"}`;
  }
  if (n === 1) return "منذ يوم";
  if (n === 2) return "منذ يومين";
  return `منذ ${n} ${n >= 3 && n <= 10 ? "أيام" : "يوم"}`;
}

